"""Generate docs/DATASET_CARD.md from the registry and the prep statistics.

Generated rather than hand-written so it cannot drift from what was actually
prepared. If the filter rules change, the card changes with them.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from dllm.config import PipelineConfig
from dllm.data.sources import get_source
from dllm.paths import DATA_PROCESSED, DOCS


def _load_stats() -> dict[str, Any]:
    path = DATA_PROCESSED / "prep_stats.json"
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def render_dataset_card(cfg: PipelineConfig) -> str:
    src = get_source(cfg.data.source)
    guard = get_source("dolly_guard")
    stats = _load_stats()
    sql = stats.get("sql", {})
    counts = sql.get("counts", {})

    dropped_total = sum(
        sql.get(k, 0)
        for k in (
            "dropped_empty",
            "dropped_unparseable",
            "dropped_not_select",
            "dropped_too_long",
            "dropped_duplicate",
            "dropped_gold_unexecutable",
        )
    )

    lines = [
        "# Dataset card",
        "",
        "> Generated by `dllm data card`. Do not edit by hand.",
        f"> Last generated: `{datetime.now(timezone.utc).isoformat(timespec='seconds')}`",
        "",
        "## Summary",
        "",
        "Natural-language question plus a `CREATE TABLE` schema, paired with the SQL",
        "query that answers it. Used to adapt a general instruct model into a",
        "text-to-SQL model whose correctness can be checked by execution rather than",
        "by human judgement.",
        "",
        "## Source",
        "",
        f"- **Hugging Face id**: `{src.hf_id}`",
        f"- **Revision**: `{src.revision}`",
        f"- **Licence**: {src.licence} ({src.licence_url})",
        f"- **Permitted use**: {src.use}",
        f"- **Homepage**: {src.homepage}",
        f"- **Citation**: {src.citation}",
        "",
        "### Provenance",
        "",
    ]
    if src.upstreams:
        lines += ["| Upstream | Licence | Notes |", "|---|---|---|"]
        for up in src.upstreams:
            lines.append(f"| [{up.name}]({up.url}) | {up.licence} | {up.note} |")
        lines.append("")
    lines += [
        "### Obligations we accept",
        "",
    ]
    lines += [f"- {o}" for o in src.obligations]
    lines += [
        "",
        "See [LICENCE_AUDIT.md](LICENCE_AUDIT.md) for the machine-generated audit, which",
        "runs before any download and fails the build on a violation.",
        "",
        "## Preparation",
        "",
        "Run with `dllm data prepare`. Every step is deterministic given the config seed.",
        "",
        "| Stage | Count |",
        "|---|---:|",
        f"| Raw rows in source | {sql.get('raw', 0):,} |",
        f"| Dropped: empty field | {sql.get('dropped_empty', 0):,} |",
        f"| Dropped: gold SQL does not parse | {sql.get('dropped_unparseable', 0):,} |",
        f"| Dropped: gold SQL is not a SELECT | {sql.get('dropped_not_select', 0):,} |",
        f"| Dropped: prompt over {cfg.data.max_prompt_chars} chars | {sql.get('dropped_too_long', 0):,} |",
        f"| Dropped: duplicate question+schema | {sql.get('dropped_duplicate', 0):,} |",
        f"| Dropped: gold SQL will not execute (eval splits) | {sql.get('dropped_gold_unexecutable', 0):,} |",
        f"| **Dropped, total** | **{dropped_total:,}** |",
        f"| **Kept after the configured cap** | **{sql.get('kept', 0):,}** |",
        "",
        "### Splits",
        "",
        "| Split | Rows | Purpose |",
        "|---|---:|---|",
        f"| train | {counts.get('train', 0):,} | LoRA fine-tuning |",
        f"| validation | {counts.get('validation', 0):,} | in-loop monitoring, checkpoint selection |",
        f"| test | {counts.get('test', 0):,} | the held-out scorecard; never trained on |",
        f"| guard | {stats.get('guard_examples', 0):,} | catastrophic-forgetting check |",
        "",
        "Splits are assigned by **content hash**, not by shuffling:",
        "",
        "```",
        "bucket = sha256(seed || item_id)[:8] / 0xFFFFFFFF",
        f"test        if bucket <  {cfg.data.test_fraction}",
        f"validation  if bucket <  {cfg.data.test_fraction + cfg.data.eval_fraction}",
        "train       otherwise",
        "```",
        "",
        "This matters more than it looks. With a shuffle, changing the row cap or adding",
        "a filter reshuffles everything, and an item that was in `test` last week can be",
        "in `train` this week — quietly invalidating every previous scorecard. Hashing",
        "the item's own content pins it to one split permanently.",
        "",
        "Deduplication runs **before** splitting, so a repeated question cannot appear in",
        "both train and test.",
        "",
        "## Guard set",
        "",
        f"- **Source**: `{guard.hf_id}` ({guard.licence})",
        f"- **Rows**: {stats.get('guard_examples', 0):,}",
        "- **Filter**: closed-book instructions only (no supplied context passage),",
        "  with anything mentioning SQL, databases, queries or tables removed.",
        "- **Not used for training.** It exists solely to detect a fine-tune that has",
        "  learned to answer every question with a SELECT statement.",
        "",
        "## Fields",
        "",
        "| Field | Description |",
        "|---|---|",
    ]
    for field_name, description in src.fields.items():
        lines.append(f"| `{field_name}` | {description} |")
    lines += [
        "",
        "Prepared rows add a stable `id` (a hash of question+schema+answer) and a",
        "`source` key.",
        "",
        "## Known limitations",
        "",
        "- **Schemas are synthetic and shallow.** Most items have a single table with",
        "  untyped-in-practice `VARCHAR` columns. A model tuned on this will be weaker on",
        "  real multi-table warehouses with foreign keys and typed columns than the",
        "  headline number suggests.",
        "- **Derived partly from Spider, which the eval also draws on.** Our own test",
        "  split is a genuine holdout of *this* dataset, but it is not an",
        "  out-of-distribution test. Treat the score as in-domain performance.",
        "- **Gold queries are not always the only correct answer.** Execution accuracy",
        "  handles most of this (a differently-written but equivalent query scores as",
        "  correct), but a query that is correct against a different reasonable reading",
        "  of an ambiguous question will still be marked wrong.",
        "- **No PII review was performed** beyond noting that the source is composed of",
        "  synthetic and public-domain sports/geography style tables. It is not suitable",
        "  as evidence of a PII-safe pipeline.",
        "",
        "## Redistribution",
        "",
        "This repository ships the **preparation script, not the prepared data**. The",
        "Spider share-alike term propagates to redistributed derivative datasets, and",
        "shipping the splits would put this repository's data under CC-BY-SA-4.0. Run",
        "`dllm data prepare` to regenerate them byte-identically from the pinned",
        "revision.",
        "",
    ]
    return "\n".join(lines)


def write_dataset_card(cfg: PipelineConfig, path: Path | None = None) -> Path:
    target = path or DOCS / "DATASET_CARD.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_dataset_card(cfg), encoding="utf-8")
    return target
