"""Licence audit: refuse to train on data whose terms do not permit the use.

Run before any download. It resolves every source a config references,
walks its declared upstreams, and produces a manifest plus a human-readable
report. It exits non-zero on a violation so CI can block on it.

The audit deliberately does not try to interpret licence text. It checks the
*declared* metadata in ``dllm.data.sources`` against the *declared* intended
use. Its job is to make an undeclared or contradictory licence impossible to
ignore, not to give legal advice.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

from dllm.data.sources import DatasetSource, get_source


class LicenceViolation(RuntimeError):
    """Raised when a selected source is not compatible with the declared use."""


def _finding(level: str, source: str, message: str) -> dict[str, str]:
    return {"level": level, "source": source, "message": message}


def audit_source(src: DatasetSource, *, require_commercial: bool) -> list[dict[str, str]]:
    """Return findings for one source. ``error`` level findings fail the audit."""
    findings: list[dict[str, str]] = []

    if src.key.endswith("_REJECTED"):
        findings.append(
            _finding(
                "error",
                src.key,
                "source is marked REJECTED in the registry and must not be used",
            )
        )

    if require_commercial and not src.commercial_ok:
        findings.append(
            _finding(
                "error",
                src.key,
                f"licence {src.licence} is {src.use}; config requires commercial use",
            )
        )

    if not src.licence or not src.licence_url:
        findings.append(_finding("error", src.key, "licence or licence_url is missing"))

    if src.revision == "main":
        findings.append(
            _finding(
                "warn",
                src.key,
                "revision is 'main' (unpinned): the dataset can change under you and "
                "eval numbers stop being reproducible",
            )
        )

    for up in src.upstreams:
        if "SA" in up.licence.upper().replace("-", ""):
            findings.append(
                _finding(
                    "warn",
                    src.key,
                    f"upstream {up.name} is share-alike ({up.licence}): redistributing "
                    f"prepared splits triggers the same licence",
                )
            )
        if "NC" in up.licence.upper().split("-"):
            findings.append(
                _finding(
                    "error",
                    src.key,
                    f"upstream {up.name} is non-commercial ({up.licence}); "
                    f"the restriction propagates to this dataset",
                )
            )

    if not src.obligations:
        findings.append(
            _finding("warn", src.key, "no obligations recorded; attribution may be missing")
        )

    return findings


def audit(
    source_keys: list[str],
    *,
    require_commercial: bool,
    base_model_licence: str | None = None,
    base_model_commercial: bool | None = None,
) -> dict:
    """Audit every source plus the base-model licence. Returns a manifest."""
    findings: list[dict[str, str]] = []
    sources: list[dict] = []

    for key in source_keys:
        src = get_source(key)
        sources.append(asdict(src))
        findings.extend(audit_source(src, require_commercial=require_commercial))

    if base_model_licence is not None and require_commercial and base_model_commercial is False:
        findings.append(
            _finding(
                "error",
                "base_model",
                f"base model licence {base_model_licence} does not permit commercial use",
            )
        )

    errors = [f for f in findings if f["level"] == "error"]
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "require_commercial_licence": require_commercial,
        "base_model_licence": base_model_licence,
        "sources": sources,
        "findings": findings,
        "error_count": len(errors),
        "warn_count": len(findings) - len(errors),
        "passed": not errors,
    }


def render_markdown(manifest: dict) -> str:
    """Human-readable audit report for docs/LICENCE_AUDIT.md."""
    lines: list[str] = [
        "# Licence audit",
        "",
        "> Generated by `dllm data audit`. Do not edit by hand.",
        "",
        f"- Generated: `{manifest['generated_at']}`",
        f"- Commercial use required: `{manifest['require_commercial_licence']}`",
        f"- Base model licence: `{manifest.get('base_model_licence')}`",
        f"- Result: **{'PASS' if manifest['passed'] else 'FAIL'}** "
        f"({manifest['error_count']} error, {manifest['warn_count']} warning)",
        "",
        "## Sources",
        "",
        "| Key | Hugging Face id | Licence | Permitted use | Commercial |",
        "|---|---|---|---|---|",
    ]
    for s in manifest["sources"]:
        commercial = "yes" if s["use"] != "research_only" else "**no**"
        lines.append(
            f"| `{s['key']}` | `{s['hf_id']}` | {s['licence']} | {s['use']} | {commercial} |"
        )

    lines += ["", "## Provenance and obligations", ""]
    for s in manifest["sources"]:
        lines.append(f"### `{s['key']}`")
        lines.append("")
        lines.append(f"{s['notes']}" if s["notes"] else "")
        lines.append("")
        if s["upstreams"]:
            lines.append("Derived from:")
            lines.append("")
            for up in s["upstreams"]:
                lines.append(f"- **{up['name']}** — {up['licence']} — {up['url']}")
                if up["note"]:
                    lines.append(f"  - {up['note']}")
            lines.append("")
        if s["obligations"]:
            lines.append("Obligations:")
            lines.append("")
            for o in s["obligations"]:
                lines.append(f"- {o}")
            lines.append("")
        lines.append(f"Citation: {s['citation']}")
        lines.append("")

    lines += ["## Findings", ""]
    if not manifest["findings"]:
        lines.append("None.")
    else:
        lines.append("| Level | Source | Message |")
        lines.append("|---|---|---|")
        for f in manifest["findings"]:
            lines.append(f"| {f['level'].upper()} | `{f['source']}` | {f['message']} |")
    lines.append("")
    return "\n".join(lines)


def write_audit(manifest: dict, json_path: Path, md_path: Path) -> None:
    json_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(render_markdown(manifest), encoding="utf-8")
